describe.skipIf(!fs.existsSync(path.join(root, "content")))("tester-style play-throughs", () => {
  for (const r of RUNS) {
    it(`${r.id}/${r.variant}: every message does what she meant`, () => {
      let sim: Sim = startSim(content, r.id, r.seed, r.variant);
      for (const l of r.lines) sim = step(content, sim, l).sim;
      const said = sim.messages.filter((m) => m.from === "examiner").map((m) => ("text" in m ? m.text : "")).join(" | ");
      expect(said).not.toMatch(/לא הבנתי|באיזה מינון/);
      expect(sim.actions.some((a) => a.action === "transport")).toBe(true);
      // Nothing from the wrong storyline or a misread word.
      for (const id of ["cutSuck", "dryBaby", "decon", "callPolice", "bvm"]) expect(sim.actions.some((a) => a.action === id), id).toBe(false);
      expect(debrief(content, sim).errors.filter((e) => !e.text.includes("מינון שגוי"))).toEqual([]);
    });
  }
});
